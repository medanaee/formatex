//! The Typst `World` of one project: the engine, the project's files, packages and fonts, seen as one project root.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::{Arc, Mutex};

use typst::diag::{FileError, FileResult};
use typst::foundations::{Bytes, Datetime, Dict, Duration, Value};
use typst::syntax::{FileId, RootedPath, Source, VirtualPath, VirtualRoot};
use typst::text::{Font, FontBook};
use typst::utils::LazyHash;
use typst::{Library, LibraryExt, World};
use typst_kit::datetime::Time;
use typst_kit::files::{FileLoader, FileStore, FsRoot};
use typst_kit::fonts::FontStore;
use typst_kit::packages::SystemPackages;

use crate::components::ComponentLibrary;
use crate::engine;

/// Where a file comes from:
/// - `extra` files (a probe's own config.toml, ...) first,
/// - `components/...` from the component library (the generated registry, the user's components, the built-in ones),
/// - `src/themes.typ` is generated from the built-in themes and the user's,
/// - the other engine files (`main.typ`, `src/`, `tools/`) are embedded in the app and cannot be shadowed,
/// - every other path of the project root is a file of the user's project folder (none for a probe),
/// - `@preview/...` paths are packages.
struct Loader {
    project: Option<FsRoot>,
    /// The project's folder on disk; a project kept in a folder of the user's (`.formatex/config.toml` exists) reads its `config.toml` from there.
    root: Option<PathBuf>,
    packages: Arc<SystemPackages>,
    components: Arc<ComponentLibrary>,
    extra: Arc<Mutex<HashMap<String, Vec<u8>>>>,
}

impl FileLoader for Loader {
    fn load(&self, id: FileId) -> FileResult<Bytes> {
        match id.root() {
            VirtualRoot::Project => {
                let path = id.vpath().get_without_slash();
                if let Some(bytes) = self.extra.lock().unwrap_or_else(|e| e.into_inner()).get(path) {
                    return Ok(Bytes::new(bytes.clone()));
                }
                if path.starts_with("components/") {
                    return self
                        .components
                        .source_for(path)
                        .map(|bytes| Bytes::new(bytes.into_owned()))
                        .ok_or_else(|| FileError::NotFound(path.into()));
                }
                // The engine's themes plus the user's (generated by the app)
                if path == "src/themes.typ" {
                    return Ok(Bytes::new(self.components.themes_source()));
                }
                if engine::owns(path) {
                    return engine::file(path)
                        .map(Bytes::new)
                        .ok_or_else(|| FileError::NotFound(path.into()));
                }
                if path == "config.toml" {
                    if let Some(config) = self.root.as_ref().map(|root| root.join(".formatex").join("config.toml")).filter(|config| config.is_file()) {
                        return std::fs::read(&config).map(Bytes::new).map_err(|error| FileError::from_io(error, &config));
                    }
                }
                match &self.project {
                    Some(project) => project.load(id.vpath()),
                    None => Err(FileError::NotFound(path.into())),
                }
            }
            VirtualRoot::Package(spec) => {
                let root = self.packages.obtain(spec).map_err(FileError::Package)?;
                root.load(id.vpath())
            }
        }
    }
}

pub struct ProjectWorld {
    library: LazyHash<Library>,
    fonts: Arc<FontStore>,
    files: FileStore<Loader>,
    time: Time,
    entry: String,
    extra: Arc<Mutex<HashMap<String, Vec<u8>>>>,
}

impl ProjectWorld {
    /// `project_dir` is the user's project folder (`None` for a probe); `entry` is the file to compile; `inputs` become
    /// `sys.inputs` (the engine reads `source` from it); `extra` are files served before anything else.
    pub fn new(
        project_dir: Option<PathBuf>,
        entry: &str,
        packages: Arc<SystemPackages>,
        fonts: Arc<FontStore>,
        components: Arc<ComponentLibrary>,
        inputs: &HashMap<String, String>,
        extra: HashMap<String, Vec<u8>>,
    ) -> Self {
        let extra = Arc::new(Mutex::new(extra));
        let mut dict = Dict::new();
        for (key, value) in inputs {
            dict.insert(key.as_str().into(), Value::Str(value.as_str().into()));
        }
        Self {
            library: LazyHash::new(Library::builder().with_inputs(dict).build()),
            fonts,
            files: FileStore::new(Loader { project: project_dir.clone().map(FsRoot::new), root: project_dir, packages, components, extra: extra.clone() }),
            time: Time::system(),
            entry: entry.to_string(),
            extra,
        }
    }

    /// Prepares the next compilation of a world kept between compilations: files are read again (a changed source is edited in
    /// place, which keeps Typst's incremental work valid) and `extra` (the editor's unsaved text) is replaced.
    pub fn refresh(&mut self, extra: HashMap<String, Vec<u8>>) {
        *self.extra.lock().unwrap_or_else(|e| e.into_inner()) = extra;
        self.files.reset();
        self.time.reset();
    }

    /// The project-relative path of a file, for messages (`None` for package files).
    pub fn display_path(id: FileId) -> Option<String> {
        matches!(id.root(), VirtualRoot::Project).then(|| id.vpath().get_without_slash().to_string())
    }
}

impl World for ProjectWorld {
    fn library(&self) -> &LazyHash<Library> {
        &self.library
    }

    fn book(&self) -> &LazyHash<FontBook> {
        self.fonts.book()
    }

    fn main(&self) -> FileId {
        RootedPath::new(VirtualRoot::Project, VirtualPath::new(&self.entry).expect("valid entry path")).intern()
    }

    fn source(&self, id: FileId) -> FileResult<Source> {
        self.files.source(id)
    }

    fn file(&self, id: FileId) -> FileResult<Bytes> {
        self.files.file(id)
    }

    fn font(&self, index: usize) -> Option<Font> {
        self.fonts.font(index)
    }

    fn today(&self, offset: Option<Duration>) -> Option<Datetime> {
        self.time.today(offset)
    }
}
