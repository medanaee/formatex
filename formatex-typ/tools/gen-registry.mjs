#!/usr/bin/env node
// Writes components/_registry.typ from every components/<name>.typ.
// Run it after adding, removing or renaming a component file (build-all.mjs, bundle.mjs and export-schema.mjs do).
//
//   node tools/gen-registry.mjs
//
// A component is one Typst file, components/<name>.typ, that exports:
//   #let <name>-tags  = ( tag: (attrs, body) => ..., ... )   required; the dictionary of tags it answers to
//   #let <name>-rules(doc) = { show ...; doc }                optional; show rules applied to the whole document
//                                                              (a #show inside an imported file does not leak out)
//   #let <name>-scope = (name: value)                          optional; merged into cmarker's scope
//   #let <name>-schema = ( tag: (kind, description, attrs, ...) )  required for every tag; see src/lib/schema.typ
// Rules run in ascending order of a comment line `// rules-order: N` (default 100).
// Tag keys are read from the lines of the tags dictionary that sit at its first key's indentation;
// a tag declared by two components stops the generator.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const escapeRegex = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** Generates the registry of the engine in `root` and returns what it found. */
export function genRegistry(root) {
  const compDir = path.join(root, "components")
  const comps = []
  const seen = new Map()

  const files = fs
    .readdirSync(compDir)
    .filter((file) => file.endsWith(".typ") && !file.startsWith("_"))
    .sort()
  for (const file of files) {
    const name = file.slice(0, -4)
    const text = fs.readFileSync(path.join(compDir, file), "utf8").replace(/\r\n/g, "\n")
    const lines = text.split("\n")
    const esc = escapeRegex(name)
    if (!new RegExp(`^#let\\s+${esc}-tags\\s*=`, "m").test(text)) throw new Error(`components/${file}: it must define #let ${name}-tags = (...)`)
    const rules = new RegExp(`^#let\\s+${esc}-rules\\b`, "m").test(text)
    const scope = new RegExp(`^#let\\s+${esc}-scope\\b`, "m").test(text)
    const schema = new RegExp(`^#let\\s+${esc}-schema\\s*=`, "m").test(text)
    const before = seen.size
    const order = Number(/^\/\/\s*rules-order:\s*(-?\d+)/m.exec(text)?.[1] ?? 100)

    // tag keys: from the "#let <name>-tags = (" line to the closing ")" in column 0
    const start = lines.findIndex((line) => new RegExp(`^#let\\s+${esc}-tags\\s*=`).test(line))
    let indent = null
    const emptyTags = /=\s*\(:\)\s*$/.test(lines[start])
    for (let i = start + 1; !emptyTags && i < lines.length && !/^\)/.test(lines[i]); i++) {
      const match = /^(\s+)("?)([A-Za-z][\w-]*)\2\s*:\s*\S/.exec(lines[i])
      if (!match) continue
      if (indent === null) indent = match[1].length
      if (match[1].length === indent) {
        const tag = match[3]
        if (seen.has(tag)) throw new Error(`tag <${tag}> is declared by both '${seen.get(tag)}' and '${name}'`)
        seen.set(tag, name)
      }
    }
    if (seen.size > before && !schema) throw new Error(`components/${file}: it declares tags but has no #let ${name}-schema`)
    comps.push({ name, rules, order, scope, schema })
  }

  const join = (items) => ["(:)", ...items].join(" + ")
  const out = ["// GENERATED by tools/gen-registry.mjs from components/*.typ. Do not edit."]
  for (const c of comps) {
    const names = [`${c.name}-tags`]
    if (c.rules) names.push(`${c.name}-rules`)
    if (c.scope) names.push(`${c.name}-scope`)
    if (c.schema) names.push(`${c.name}-schema`)
    out.push(`#import "/components/${c.name}.typ": ${names.join(", ")}`)
  }
  out.push('#import "/src/lib/schema.typ": wrap-tags', "")
  out.push(`#let raw-tags = ${join(comps.map((c) => `${c.name}-tags`))}`)
  out.push(`#let all-schemas = ${join(comps.filter((c) => c.schema).map((c) => `${c.name}-schema`))}`)
  out.push("#let html-tags = wrap-tags(raw-tags, all-schemas)")
  out.push(`#let scope-extras = ${join(comps.filter((c) => c.scope).map((c) => `${c.name}-scope`))}`, "")
  out.push("#let all-rules(doc) = {")
  for (const c of comps.filter((c) => c.rules).sort((a, b) => a.order - b.order || a.name.localeCompare(b.name))) out.push(`  show: ${c.name}-rules`)
  out.push("  doc", "}")

  fs.writeFileSync(path.join(compDir, "_registry.typ"), out.join("\n") + "\n")
  return { components: comps.length, tags: seen.size }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  try {
    const { components, tags } = genRegistry(root)
    console.log(`registry: ${components} components, ${tags} tags`)
  } catch (error) {
    console.error(`gen-registry: ${error.message}`)
    process.exit(1)
  }
}
